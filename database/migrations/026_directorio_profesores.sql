-- 1) Profesores nuevos; los que ya existen no se tocan (conservan lo que el profesor corrigió), salvo género y RFC completo si faltaban.
INSERT IGNORE INTO profesores (rfc10, rfc, nombre, apellido1, apellido2, genero, observaciones)
SELECT rfc10, rfc, nombre, apellido1, apellido2, genero, observaciones FROM tmp_prof;
UPDATE profesores p JOIN tmp_prof t ON t.rfc10 = p.rfc10
SET p.genero = IFNULL(p.genero, t.genero), p.rfc = IF(CHAR_LENGTH(p.rfc) < CHAR_LENGTH(t.rfc), t.rfc, p.rfc);

-- 2) Correos (uno por persona; si ya pertenece a alguien, se conserva) y adscripciones del periodo 2026B.
INSERT IGNORE INTO profesor_correos (profesor_id, email, principal)
SELECT p.id, c.email, IF(EXISTS (SELECT 1 FROM profesor_correos x WHERE x.profesor_id = p.id AND x.principal = 1), 0, c.principal)
FROM tmp_prof_correo c JOIN profesores p ON p.rfc10 = c.rfc10;
INSERT IGNORE INTO profesor_adscripciones (profesor_id, unidad_id, periodo, fecha_inicio)
SELECT p.id, u.id, '2026B', '2026-08-01' FROM tmp_prof_unidad t JOIN profesores p ON p.rfc10 = t.rfc10 JOIN profesor_unidades u ON u.clave = t.clave;

-- 3) Profesores que ya tienen cuenta (su correo coincide y no hay otra persona enlazada a esa cuenta): se enlazan, sin crear otro registro.
UPDATE profesores p
JOIN profesor_correos c ON c.profesor_id = p.id
JOIN usuarios u ON u.email = c.email
SET p.usuario_id = u.id
WHERE p.usuario_id IS NULL AND NOT EXISTS (SELECT 1 FROM (SELECT usuario_id FROM profesores WHERE usuario_id IS NOT NULL) y WHERE y.usuario_id = u.id);
UPDATE usuarios u JOIN profesores p ON p.usuario_id = u.id SET u.genero = p.genero WHERE u.genero IS NULL AND p.genero IS NOT NULL;

-- 4) Los programas de los profesores con cuenta pasan a programa_profesores (adscripción docente vigente, sin repetir).
INSERT IGNORE INTO programa_profesores (programa_id, usuario_id, tipo_vinculo, fecha_inicio, activo, observaciones)
SELECT un.programa_id, p.usuario_id, 'docente', a.fecha_inicio, 1, 'Directorio de profesores 2026B'
FROM profesor_adscripciones a JOIN profesores p ON p.id = a.profesor_id AND p.usuario_id IS NOT NULL
JOIN profesor_unidades un ON un.id = a.unidad_id AND un.programa_id IS NOT NULL
WHERE a.periodo = '2026B';

-- 5) Correos del historial de actas (tit_historico): se completan, sin pisar los que ya tienen, cuando el nombre (sin importar acentos
--    ni mayúsculas, con o sin grado) coincide con un solo profesor del directorio. El correo del director solo se asigna si no hay
--    codirector: con dos asesores el sistema anterior no distingue sus roles y deben confirmarse a mano.
UPDATE tit_historico h SET h.director_email = IFNULL((SELECT MIN(c.email) FROM profesores p JOIN profesor_correos c ON c.profesor_id = p.id AND c.principal = 1 WHERE h.director COLLATE utf8mb4_spanish_ci = CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2) OR h.director COLLATE utf8mb4_spanish_ci LIKE CONCAT('% ', CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2)) HAVING COUNT(DISTINCT p.id) = 1), '') WHERE h.director_email = '' AND h.director <> '' AND h.tramite_id IS NULL AND h.codirector = '';
UPDATE tit_historico h SET h.presidente_email = IFNULL((SELECT MIN(c.email) FROM profesores p JOIN profesor_correos c ON c.profesor_id = p.id AND c.principal = 1 WHERE h.presidente COLLATE utf8mb4_spanish_ci = CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2) OR h.presidente COLLATE utf8mb4_spanish_ci LIKE CONCAT('% ', CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2)) HAVING COUNT(DISTINCT p.id) = 1), '') WHERE h.presidente_email = '' AND h.presidente <> '' AND h.tramite_id IS NULL;
UPDATE tit_historico h SET h.secretario_email = IFNULL((SELECT MIN(c.email) FROM profesores p JOIN profesor_correos c ON c.profesor_id = p.id AND c.principal = 1 WHERE h.secretario COLLATE utf8mb4_spanish_ci = CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2) OR h.secretario COLLATE utf8mb4_spanish_ci LIKE CONCAT('% ', CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2)) HAVING COUNT(DISTINCT p.id) = 1), '') WHERE h.secretario_email = '' AND h.secretario <> '' AND h.tramite_id IS NULL;
UPDATE tit_historico h SET h.vocal_email = IFNULL((SELECT MIN(c.email) FROM profesores p JOIN profesor_correos c ON c.profesor_id = p.id AND c.principal = 1 WHERE h.vocal COLLATE utf8mb4_spanish_ci = CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2) OR h.vocal COLLATE utf8mb4_spanish_ci LIKE CONCAT('% ', CONCAT_WS(' ', p.nombre, p.apellido1, p.apellido2)) HAVING COUNT(DISTINCT p.id) = 1), '') WHERE h.vocal_email = '' AND h.vocal <> '' AND h.tramite_id IS NULL;
